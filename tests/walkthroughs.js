// Komplette Lösungswege je Abschnitt, gespielt nur über Eingaben in der echten Physik.
// Jeder Abschnitt beginnt am Spawn/Checkpoint und endet am nächsten Checkpoint bzw. im Ziel.
const { Sim, go, hop, ride, leap, press, wait, until, pushTo, mount, par, only, E, J, R, L, C, P } = require('./lib');
const opened = (r, i, v = 0.95) => r.s.gates[i].o >= v;
const gate = (r, color, sec) => r.w.gates.findIndex(g => g.color === color && (sec === undefined || g.s === sec));
const both = (r, a, b, o0, o1) => par(r, go(r, 0, a, o0), go(r, 1, b, o1));
const toCp = (r, i) => function* () {
  const c = r.w.cps[i];
  yield* both(r, c.flag[0] - 40, c.flag[0] + 40);
  yield* par(r, until(r, q => q.s.cp > i, 'Checkpoint ' + i, 200));
};
const toExit = r => function* () {
  const e = r.w.exit;
  yield* both(r, e.x + 50, e.x + 100);
  yield* par(r, until(r, q => q.s.phase === 'done', 'Levelabschluss', 200));
};
// Räuberleiter: base steht bei x, rider steigt auf den Kopf
function* stack(r, base, x) {
  const rider = 1 - base;
  yield* only(r, base, go(r, base, x));
  yield* only(r, rider, mount(r, rider, base));
}
const seq = (...fs) => function* () { for (const f of fs) yield* (typeof f === 'function' ? f() : f); };

